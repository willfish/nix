def render(
    mode,
    palette,
    font="Liberation Sans",
    mono="JetBrainsMono Nerd Font",
    font_size=12,
):
    expression = f"""
      let
        hyprland = import {HYPRLAND} {{}};
        palette = builtins.fromJSON ''{json.dumps(palette)}'';
        appearance = {{
          font = {json.dumps(font)};
          monoFont = {json.dumps(mono)};
          fontSize = {font_size};
          rounding = 8;
          borderSize = 2;
          colors = {{}};
        }};
        rendered = hyprland.render {{
          mode = {json.dumps(mode)};
          inherit palette appearance;
        }};
      in {{
        assets = hyprland.assets;
        walker = hyprland.walker;
        names = builtins.attrNames rendered;
        css = rendered."walker.css";
      }}
    """
    raw = subprocess.check_output(
        ["nix", "eval", "--impure", "--json", "--expr", expression],
        text=True,
    )
    return json.loads(raw)


class LauncherThemeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.dark = render("dark", DARK)
        cls.light = render(
            "light",
            LIGHT,
            font='Quote "Face"',
            mono="Mono\\Face",
            font_size=14,
        )

    def test_theme_contract_and_seed_assets(self):
        for rendered in (self.dark, self.light):
            self.assertEqual(rendered["walker"]["theme"], "hyprland")
            self.assertEqual(rendered["walker"]["stylesheet"], "walker.css")
            self.assertEqual(
                rendered["walker"]["activePath"],
                ".local/state/theme-menu/active/walker.css",
            )
            self.assertIn("walker.css", rendered["assets"])
            self.assertIn("fuzzel.ini", rendered["assets"])
            missing = set(rendered["assets"]) - set(rendered["names"])
            self.assertEqual(missing, set())

    def test_css_uses_palette_fonts_and_walker_selectors(self):
        css = self.dark["css"]
        self.assertIn("Selected mode: dark. Generated by theme-menu.", css)
        self.assertIn("@define-color window_bg_color #000000;", css)
        self.assertIn("@define-color accent_bg_color #0d0d0d;", css)
        self.assertIn("@define-color selection #020202;", css)
        self.assertIn("@define-color muted #040404;", css)
        self.assertIn("@define-color error_bg_color #080808;", css)
        self.assertIn(
            'font-family: "Liberation Sans", "JetBrainsMono Nerd Font";',
            css,
        )
        self.assertIn("font-size: 12pt;", css)
        self.assertIn("font-size: 10pt;", css)
        self.assertIn("border-radius: 8px;", css)
        self.assertIn("border: 2px solid @accent_bg_color;", css)
        self.assertIn("background-color: transparent;", css)
        for selector in REQUIRED_SELECTORS:
            self.assertIn(selector, css)
        self.assertNotIn(
            "theme-menu", css.split("Generated by theme-menu.", 1)[1]
        )

    def test_light_mode_and_font_escaping_differ_from_dark(self):
        css = self.light["css"]
        self.assertIn("Selected mode: light. Generated by theme-menu.", css)
        self.assertIn("@define-color window_bg_color #0f0f0f;", css)
        self.assertNotIn("@define-color window_bg_color #000000;", css)
        self.assertIn('font-family: "Quote \\"Face\\"", "Mono\\\\Face";', css)
        self.assertIn("font-size: 14pt;", css)
        self.assertIn("font-size: 12pt;", css)


