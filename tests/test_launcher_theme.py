WALKER_RESTART = ["systemctl", "--user", "try-restart", "walker.service"]


class WalkerPublishReloadTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        catalogue = {
            "default": "tokyo-night",
            "palettes": {
                "tokyo-night": {"id": "tokyo-night", "label": "Tokyo Night"}
            },
        }
        self.controller = menu.Themes(
            catalogue,
            root / "state",
            root / "config",
            root / "greeter",
        )

    def publish(self, walker_installed, run_side_effect=None):
        def which(name):
            if name == "walker":
                return "/bin/walker" if walker_installed else None
            return f"/bin/{name}"

        with (
            patch.dict(menu.os.environ, {"THEME_MENU_PUBLISH": "1"}),
            patch.object(menu, "hyprland_session", return_value=True),
            patch.object(menu.shutil, "which", side_effect=which),
            patch.object(self.controller, "publish_greeter", return_value=[]),
            patch.object(self.controller, "_publish_gtk", return_value=[]),
            patch.object(self.controller, "_install_gtk_css", return_value=[]),
            patch.object(self.controller, "_reload_hyprland", return_value=[]),
            patch.object(self.controller, "_reload_waybar", return_value=[]),
            patch.object(menu.subprocess, "run") as run,
        ):
            if run_side_effect is None:
                run.return_value.returncode = 0
            else:
                run.side_effect = run_side_effect
            warnings = self.controller.publish_session()
        return warnings, run

    def test_hyprland_publish_restarts_walker_when_installed(self):
        warnings, run = self.publish(True)
        walker_calls = [
            call
            for call in run.call_args_list
            if call.args[0] == WALKER_RESTART
        ]
        self.assertEqual(len(walker_calls), 1)
        self.assertEqual(
            walker_calls[0].kwargs,
            {"capture_output": True, "timeout": 10, "check": True},
        )
        self.assertNotIn(
            "Launcher will use the theme on next startup.", warnings
        )

    def test_hyprland_publish_skips_walker_restart_when_absent(self):
        warnings, run = self.publish(False)
        for call in run.call_args_list:
            self.assertNotIn("walker.service", call.args[0])
        self.assertNotIn(
            "Launcher will use the theme on next startup.", warnings
        )

    def test_walker_restart_failure_warns_without_blocking_publish(self):
        def fail_walker(argv, **kwargs):
            if argv == WALKER_RESTART:
                raise subprocess.CalledProcessError(1, argv, stderr="failed")
            return subprocess.CompletedProcess(argv, 0)

        warnings, run = self.publish(True, fail_walker)
        self.assertIn("Launcher will use the theme on next startup.", warnings)
        self.assertEqual(run.call_args_list[0].args[0], WALKER_RESTART)
        self.assertIn(
            ["makoctl", "reload"],
            [call.args[0] for call in run.call_args_list],
        )

        def missing_systemctl(argv, **kwargs):
            if argv == WALKER_RESTART:
                raise OSError("systemctl missing")
            return subprocess.CompletedProcess(argv, 0)

        warnings, run = self.publish(True, missing_systemctl)
        self.assertIn("Launcher will use the theme on next startup.", warnings)
        self.assertTrue(run.called)


